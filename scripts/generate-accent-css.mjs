#!/usr/bin/env node
/**
 * Generate src/tokens/themes/_accents.css from COLOR_ACCENTS in
 * src/lib/theme-data.js (vanilla-breeze-5z8i).
 *
 * Accent presets (ocean, forest, sunset, …) used to exist only as inline
 * seeds that ThemeManager.setAccent() writes on :root, so
 * data-theme="forest" on an element did nothing, and even setting the seeds
 * there would not help: --color-primary and friends are computed once on
 * :root and inherited as finished values. Each generated rule sets the
 * accent's seeds AND re-derives the brand colours at its own scope, so an
 * accent works on <html> or on any element via data-accent.
 *
 *   node scripts/generate-accent-css.mjs          write the file
 *   node scripts/generate-accent-css.mjs --check  exit 1 if it is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { COLOR_ACCENTS } from '../src/lib/theme-data.js';

const OUT = resolve(import.meta.dirname, '../src/tokens/themes/_accents.css');

// Mirrors the BRAND COLORS block in src/tokens/colors.css.
const DERIVED = `
    --color-primary: oklch(var(--lightness-primary) var(--chroma-primary) var(--hue-primary));
    --color-primary-hover: oklch(from var(--color-primary) calc(l - 0.08) calc(c + 0.02) h);
    --color-primary-active: oklch(from var(--color-primary) calc(l - 0.12) c h);
    --color-primary-subtle: oklch(from var(--color-primary) 0.95 0.03 h);
    --color-secondary: oklch(var(--lightness-secondary) var(--chroma-secondary) var(--hue-secondary));
    --color-secondary-hover: oklch(from var(--color-secondary) calc(l - 0.08) c h);
    --color-secondary-subtle: oklch(from var(--color-secondary) 0.95 0.03 h);
    --color-accent: oklch(var(--lightness-accent) var(--chroma-accent) var(--hue-accent));
    --color-accent-hover: oklch(from var(--color-accent) calc(l - 0.08) c h);
    --color-accent-subtle: oklch(from var(--color-accent) 0.95 0.03 h);
    --color-interactive: var(--color-primary);
    --color-interactive-hover: var(--color-primary-hover);
    --color-interactive-active: var(--color-primary-active);
    --color-hover-text: var(--color-interactive);
    --color-active-text: var(--color-interactive);
    --color-border-focus: var(--color-primary);
    --color-focus-ring: var(--color-primary);
    --focus-ring-color: var(--color-focus-ring);`;

// Mirrors the auto-contrast block in src/tokens/colors.css. Those tokens are
// computed on :root, so without re-declaring them a scoped accent would keep
// the page's text-on-brand colour.
const DERIVED_AUTO = `
      --color-text-on-primary-auto: contrast-color(var(--color-primary));
      --color-text-on-secondary-auto: contrast-color(var(--color-secondary));
      --color-text-on-accent-auto: contrast-color(var(--color-accent));
      --color-text-on-interactive-auto: contrast-color(var(--color-interactive));`;

const decls = (seeds) => Object.entries(seeds).map(([k, v]) => `    ${k}: ${v};`).join('\n');

export function renderAccentCss() {
  const accents = COLOR_ACCENTS.filter((a) => a.id !== 'default' && Object.keys(a.seeds).length);
  const blocks = accents.map((a) => {
    const at = `[data-accent~="${a.id}"]`;
    let css = `  /* ${a.name} */\n  :root${at},\n  ${at} {\n${decls(a.seeds)}\n  }\n`;
    if (a.seedsDark) {
      css += `\n  :root${at}[data-mode="dark"],\n  ${at}[data-mode="dark"],\n  [data-mode="dark"] ${at} {\n${decls(a.seedsDark)}\n  }\n`;
      css += `\n  @media (prefers-color-scheme: dark) {\n    :root${at}:not([data-mode="light"]),\n    :root:not([data-mode="light"]) ${at}:not([data-mode="light"] ${at}) {\n${decls(a.seedsDark).replace(/^/gm, '  ')}\n    }\n  }\n`;
    }
    return css;
  });
  return `/* @generated by scripts/generate-accent-css.mjs from src/lib/theme-data.js — do not edit. */
/*
 * Colour accents: data-accent="ocean|forest|…" on <html> or any element (5z8i).
 * A separate axis from data-theme. Accents set the brand seeds, so they tint
 * the seed-based themes (default, modern, minimal, classic); themes that fix
 * their own --color-primary keep their palette.
 *
 * Imported after the brand themes so a specificity tie with their seed rules
 * goes to the accent. The derived colours below (brand, interactive, focus
 * ring and the text-on-brand auto colours) are re-declared at zero
 * specificity, so a scoped accent repaints buttons, links and focus rings
 * inside it; any theme that sets them concretely on the same element still
 * wins.
 */
@layer bundle-theme {
  :where([data-accent]) {${DERIVED}
  }

  @supports (color: contrast-color(red)) {
    :where([data-accent]) {${DERIVED_AUTO}
    }
  }

${blocks.join('\n')}}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const css = renderAccentCss();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (current !== css) {
      console.error('src/tokens/themes/_accents.css is stale: run node scripts/generate-accent-css.mjs');
      process.exit(1);
    }
    console.log('accents css up to date');
  } else {
    writeFileSync(OUT, css);
    console.log(`wrote ${OUT.replace(process.cwd() + '/', '')}`);
  }
}
