#!/usr/bin/env node
/**
 * Generate src/packs/ambient/ambient.icons.css: the ambient pack's motif
 * icons as data-URI custom properties, from the Lucide sources in
 * src/icons/lucide (ISC licence, already shipped with Vanilla Breeze).
 *
 *   node scripts/generate-ambient-icons.mjs          write the file
 *   node scripts/generate-ambient-icons.mjs --check  exit 1 if it is stale
 *
 * tests/unit/ambient-icons.test.js runs the check.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/packs/ambient/ambient.icons.css');

/** Ambient icon name → Lucide file. The names are the pack's closed icon vocabulary. */
export const ICONS = {
  snowflake: 'snowflake',
  sprout: 'sprout',
  sun: 'sun',
  leaf: 'leaf',
  moon: 'moon',
  cloud: 'cloud',
  drops: 'droplets',
  fog: 'cloud-fog',
  wind: 'wind',
  storm: 'cloud-lightning',
  sparkles: 'sparkles',
  cake: 'cake',
  heart: 'heart',
  ghost: 'ghost',
  star: 'star',
  flag: 'flag',
  pi: 'pi',
  gift: 'gift',
};

/** A Lucide file reduced to its shapes, as a mask-ready data URI. */
function dataUri(file) {
  const svg = readFileSync(join(ROOT, 'src/icons/lucide', `${file}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .replace(/ \/>/g, '/>')
    .replace(/> </g, '><')
    .trim();
  const min = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='#000' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${inner.replace(/"/g, "'")}</svg>`;
  return `data:image/svg+xml,${min.replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}`;
}

export function generate() {
  const lines = Object.entries(ICONS).map(([name, file]) => `    --ambient-icon-${name}: url("${dataUri(file)}");`);
  return `/* GENERATED by scripts/generate-ambient-icons.mjs from src/icons/lucide (Lucide, ISC licence).
   Do not edit: change the ICONS map in the script and run it again. */
@layer bundle-effects {
  :root[data-ambient] {
${lines.join('\n')}
  }
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = generate();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== css) {
      console.error('ambient.icons.css is stale: run node scripts/generate-ambient-icons.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, css);
    console.log(`wrote ${OUT} (${Object.keys(ICONS).length} icons, ${css.length} bytes)`);
  }
}
